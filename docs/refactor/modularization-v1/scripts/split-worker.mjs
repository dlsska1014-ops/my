#!/usr/bin/env node
// One-time positional split of src/index.js into module files, driven by a line-range manifest.
//
//   node tools/split-worker.mjs --manifest docs/refactor/modularization-v1/split-manifest.txt
//
// The manifest is tab-separated with a header row; the columns used are: path, start_line, end_line.
// Ranges must be contiguous, start at line 1 and end at the last line. Each module file is the
// exact byte slice of its lines including the newline that ends its last line, so the plain
// concatenation of the files reproduces the source. The script refuses to finish unless the
// SHA-256 of that concatenation equals the source file, and it writes src/modules/MANIFEST.txt
// (output order) for tools/build-worker.mjs.
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const args = process.argv.slice(2);
const option = (name, fallback) => { const i = args.indexOf(name); return i >= 0 && args[i + 1] && !args[i + 1].startsWith("--") ? args[i + 1] : fallback; };
const sourcePath = resolve(root, option("--source", "src/index.js"));
const modulesRoot = resolve(root, option("--modules", "src/modules"));
const manifestPath = resolve(root, option("--manifest", "docs/refactor/modularization-v1/split-manifest.txt"));
const force = args.includes("--force");

const source = readFileSync(sourcePath, "utf8");
if (source.includes("\r")) throw new Error("source contains CR; expected LF-only file");
if (!source.endsWith("\n")) throw new Error("source must end with a newline");
// offsets[n] is the character offset where line n (1-based) starts; offsets[lineCount + 1] is source.length.
const offsets = [0, 0];
for (let i = 0; i < source.length; i += 1) if (source.charCodeAt(i) === 10) offsets.push(i + 1);
const lineCount = offsets.length - 2; // the final "\n" starts an empty "line" we do not count

const rows = readFileSync(manifestPath, "utf8").split(/\r?\n/).filter((l) => l.trim());
const header = rows.shift().split("\t");
const col = (name) => { const i = header.indexOf(name); if (i < 0) throw new Error(`manifest column missing: ${name}`); return i; };
const [cPath, cStart, cEnd] = [col("path"), col("start_line"), col("end_line")];
const entries = rows.map((r) => r.split("\t")).map((cells) => ({ path: cells[cPath], start: Number(cells[cStart]), end: Number(cells[cEnd]) }));

let expected = 1;
for (const e of entries) {
  if (!/^[a-z0-9-]+\/[a-z0-9-]+\.js$/.test(e.path)) throw new Error(`${e.path}: unexpected module path`);
  if (e.start !== expected) throw new Error(`${e.path}: starts at ${e.start}, expected ${expected} (ranges must be contiguous)`);
  if (e.end < e.start) throw new Error(`${e.path}: end before start`);
  expected = e.end + 1;
}
if (expected - 1 !== lineCount) throw new Error(`manifest covers ${expected - 1} lines, source has ${lineCount}`);
if (existsSync(resolve(modulesRoot, "MANIFEST.txt")) && !force) throw new Error(`${modulesRoot}/MANIFEST.txt exists; pass --force to overwrite`);

const parts = [];
for (const e of entries) {
  const text = source.slice(offsets[e.start], offsets[e.end + 1]);
  const target = resolve(modulesRoot, e.path);
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, text);
  parts.push(text);
}
const sha256 = (t) => createHash("sha256").update(t).digest("hex");
const rebuilt = parts.join("");
if (sha256(rebuilt) !== sha256(source)) throw new Error("rebuilt output differs from source; aborting (files were written, inspect before retrying)");
writeFileSync(resolve(modulesRoot, "MANIFEST.txt"), `# build order for tools/build-worker.mjs (generated by tools/split-worker.mjs)\n${entries.map((e) => e.path).join("\n")}\n`);
console.log(`split ${entries.length} modules into ${modulesRoot}; rebuilt sha256 ${sha256(rebuilt)} == source`);
